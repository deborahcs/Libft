void	*ft_memchr(const void *s, int c, size_t n)
{
	size_t	i;
	unsigned char	array;
	
	i = 0;
	array = ((void *)s);
	while (i < n)
	{
		ft_strchr(c);
		i++;
	}
	return (NULL);
}
